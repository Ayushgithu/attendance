import { v2 as cloudinary } from "cloudinary";

// Config comes from env: either CLOUDINARY_URL=cloudinary://key:secret@cloud
// or the three separate variables below.
const FOLDER = "attendance-faces";

export function isCloudinaryConfigured() {
    return !!(
        process.env.CLOUDINARY_URL ||
        (process.env.CLOUDINARY_CLOUD_NAME && process.env.CLOUDINARY_API_KEY && process.env.CLOUDINARY_API_SECRET)
    );
}

function configure() {
    if (process.env.CLOUDINARY_URL) return; // the SDK reads it by itself
    cloudinary.config({
        cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
        api_key: process.env.CLOUDINARY_API_KEY,
        api_secret: process.env.CLOUDINARY_API_SECRET,
        secure: true,
    });
}

/**
 * Uploads a face photo as an *authenticated* asset: it is not reachable by a plain URL,
 * only through signed URLs generated by this server. Returns the Cloudinary public_id,
 * which is what we store in `Student.avatar`.
 */
export async function uploadFacePhoto(buffer: Buffer): Promise<string> {
    configure();
    return new Promise((resolve, reject) => {
        cloudinary.uploader
            .upload_stream(
                {
                    folder: FOLDER,
                    resource_type: "image",
                    type: "authenticated",
                    format: "jpg",
                    overwrite: false,
                    unique_filename: true,
                },
                (err, result) => (err || !result ? reject(err ?? new Error("Upload failed")) : resolve(result.public_id))
            )
            .end(buffer);
    });
}

/** True if `avatar` (as stored in the database) is a Cloudinary public_id rather than a local file name. */
export const isCloudinaryId = (avatar?: string | null) => !!avatar && avatar.startsWith(`${FOLDER}/`);

/** Short-lived signed URL for viewing a stored face photo (e.g. in an admin screen). */
export function signedPhotoUrl(publicId: string, expiresInSeconds = 300) {
    configure();
    return cloudinary.url(publicId, {
        type: "authenticated",
        sign_url: true,
        secure: true,
        format: "jpg",
        expires_at: Math.floor(Date.now() / 1000) + expiresInSeconds,
    } as any);
}
